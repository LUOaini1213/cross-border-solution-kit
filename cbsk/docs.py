"""Generated documentation: README numbers, data-provenance table and the regulatory check log."""
from __future__ import annotations

import json
import re
from pathlib import Path

from .io import DOCS, PUBLIC, REFERENCE, load_yaml

PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}")
LABEL_TEXT = {
    "REAL": "taken from an official source, public dataset or public index page (URL and access date given)",
    "ASSUMPTION": "modelling choice, or a placeholder where an official value could not be verified",
    "ILLUSTRATIVE": "example commercial rate; scale anchored to public indices, not a quote or tariff",
    "SYNTHETIC": "fictional RFQ data (customer, volumes, values, weights)",
}


def _esc(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _link(sources: dict, sid: str) -> str:
    s = sources.get(sid)
    return f"[{sid}]({s['url']})" if s else sid


# ------------------------------------------------------------------------------------------------ README
def readme_values(results: dict[str, dict], statements: dict, mutation: dict | None) -> dict[str, str]:
    v: dict[str, str] = {}
    for name, res in results.items():
        for s in res["summary"]:
            k = f"{name}.{s['lane']}"
            v[f"{k}.option"] = s["label_en"]
            v[f"{k}.cost"] = f"{s['cost_per_unit']:,.2f}" if s["cost_per_unit"] < 100 else f"{s['cost_per_unit']:,.0f}"
            v[f"{k}.p90"] = f"{s['p90']:.1f}"
            v[f"{k}.ontime"] = f"{s['on_time_probability'] * 100:.0f}%"
            v[f"{k}.risk"] = f"{s['risk']:.0f}"
            v[f"{k}.status"] = "meets target" if s["status"] == "meets_target" else "below target"
        v[f"{name}.quote_total"] = f"{sum(s['annual_quote'] for s in res['summary']):,.0f}"
        v[f"{name}.landed_total"] = f"{sum(s['annual_landed'] for s in res['summary']):,.0f}"
        v[f"{name}.options"] = str(sum(len(ln["options"]) for ln in res["lanes"]))
        v[f"{name}.excluded"] = str(sum(len(ln["excluded"]) for ln in res["lanes"]))
        v[f"{name}.draws"] = f"{res['monte_carlo_draws']:,}"
    auto = results.get("automotive_ckd_cn_my")
    if auto:
        rows = [r for ln in auto["lanes"] for r in ln["extra"]["fta"]]
        v["auto.duty_mfn"] = f"{sum(r['mfn_rate'] * r['annual_goods_value'] for r in rows):,.0f}"
        v["auto.duty_chosen"] = f"{sum(r['chosen']['rate'] * r['annual_goods_value'] for r in rows):,.0f}"
        lost = [r for r in rows if r["chosen"]["scheme"] == "MFN" and r["saving_if_qualified"] > 0]
        v["auto.duty_at_stake"] = f"{sum(r['saving_if_qualified'] for r in lost):,.0f}"
    labels: dict[str, set] = {}
    for res in results.values():
        for a in res["assumptions"]:
            labels.setdefault(a["label"], set()).add(a["id"])
        for p in res["provenance"]:
            labels.setdefault(p["label"], set()).add(p["id"])
    for lab in ("REAL", "ASSUMPTION", "ILLUSTRATIVE", "SYNTHETIC"):
        v[f"prov.{lab}"] = str(len(labels.get(lab, set())))
    counts: dict[str, int] = {}
    for st in statements.values():
        counts[st["status"]] = counts.get(st["status"], 0) + 1
    for k in ("verified", "corrected", "not_verified"):
        v[f"reg.{k}"] = str(counts.get(k, 0))
    v["reg.total"] = str(len(statements))
    if mutation:
        v["mut.killed"] = str(mutation["killed"])
        v["mut.total"] = str(mutation["total"])
        v["mut.unit_killed"] = str(mutation["killed_by_unit_tests"])
        v["mut.tests"] = str(mutation.get("tests_collected", "?"))
    else:
        v["mut.killed"] = v["mut.total"] = v["mut.unit_killed"] = v["mut.tests"] = "not run"
    return v


def render_template(text: str, values: dict[str, str]) -> str:
    def repl(m):
        key = m.group(1)
        if key not in values:
            raise KeyError(f"README placeholder without a value: {key}")
        return values[key]
    return PLACEHOLDER.sub(repl, text)


# ------------------------------------------------------------------------------------------------ provenance
def provenance_md(results: dict[str, dict], sources: dict) -> str:
    rates = load_yaml(REFERENCE / "rates.yaml")
    lpi_meta = json.loads((PUBLIC / "lpi_dwell.meta.json").read_text(encoding="utf-8"))
    geo_meta = json.loads((PUBLIC / "geo.meta.json").read_text(encoding="utf-8"))
    tar_meta = json.loads((PUBLIC / "my_tariff_lines.meta.json").read_text(encoding="utf-8"))
    L = ["# Data provenance", "",
         "Generated by `scripts/build_all.py` from the inputs the models actually read (every parameter goes through the "
         "provenance-tracking loader). Labels:", ""]
    for k, t in LABEL_TEXT.items():
        L.append(f"- **{k}**: {t}")
    L += ["", "## Public datasets (REAL)", "",
          "| Dataset | File | Source | Accessed | Licence / note |", "|---|---|---|---|---|",
          f"| World Bank LPI 2.0 dwell times (2023-2024) | data/public/lpi_dwell.csv | {lpi_meta['source']} | {lpi_meta['accessed']} | "
          f"{lpi_meta['licence']}; raw SHA-256 {lpi_meta['raw_sha256'][:16]}...; {_esc(lpi_meta['note'])} |",
          f"| Airport great-circle distances | data/public/geo_air.csv | {geo_meta['airports_source']} | {geo_meta['accessed']} | "
          f"{geo_meta['airports_licence']} |",
          f"| Sea route distances | data/public/geo_sea.csv | {_esc(geo_meta['sea_tool'])} | {geo_meta['accessed']} | "
          f"{_esc(geo_meta['sea_restrictions'])} |",
          f"| Malaysian tariff lines (MFN, SST column, ACFTA, RCEP, ATIGA) | data/public/my_tariff_lines.csv | {tar_meta['source']} | "
          f"{tar_meta['accessed']} | {_esc(tar_meta['note'])} |", ""]
    L += ["## Public index anchors (REAL, scale reference only)", "",
          "Freight and handling rates in `data/reference/rates.yaml` are ILLUSTRATIVE; these index values fix their order of magnitude.", "",
          "| Index | Value | Unit | Date | Source | Note |", "|---|---|---|---|---|---|"]
    for k, a in rates["anchors"].items():
        L.append(f"| {k} | {a['value']:,} | {a['unit']} | {a['date']} | {_link(sources, a['source'])} | {_esc(a.get('note', ''))} |")
    L += ["", "## Every parameter used by the templates", "",
          "| Parameter | Value | Unit | Label | Sources (accessed) | Templates | Note |", "|---|---|---|---|---|---|---|"]
    merged: dict[str, dict] = {}
    for name, res in results.items():
        for p in res["provenance"]:
            e = merged.setdefault(p["id"], {**p, "templates": set()})
            e["templates"].add(name)
        for a in res["assumptions"]:
            e = merged.setdefault(a["id"], {"id": a["id"], "value": a["value"], "unit": a["unit"], "label": a["label"],
                                             "sources": a["sources"], "note": a["desc_en"], "templates": set()})
            e["templates"].add(name)
    for pid in sorted(merged):
        e = merged[pid]
        val = e["value"]
        if isinstance(val, float):
            val = f"{val:,.6g}"
        elif isinstance(val, (list, dict)):
            val = json.dumps(val, ensure_ascii=False)[:80]
        srcs = ", ".join(f"{_link(sources, s)} ({sources[s]['accessed']})" for s in e.get("sources", []) if s in sources) or "-"
        L.append(f"| `{pid}` | {_esc(val)} | {_esc(e.get('unit', ''))} | {e['label']} | {srcs} | "
                 f"{', '.join(sorted(e['templates']))} | {_esc(e.get('note', ''))} |")
    L += ["", "## RFQ inputs (SYNTHETIC)", "",
          "All customers are fictional (\"Customer A\"). Volumes, values, weights, kit contents, parcel mixes and movement counts in "
          "`templates/*/rfq.yaml` are invented for the examples.", ""]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------------------------------------ regulatory check
def regulatory_md(statements: dict, sources: dict, log: dict | None) -> str:
    L = ["# Regulatory check log", "",
         "Regulatory mistakes are the main risk in this project, so every regulatory or tax statement the kit relies on is kept in "
         "`data/reference/regulatory_statements.yaml` with its sources and status, and was checked twice:", "",
         "1. **Research pass (2026-11-15).** Each statement was written from the official page or legal text (government, statutory "
         "body or treaty secretariat), saved locally and read in full; secondary sources were only used to find the official one.",
         "2. **Separate re-check pass.** `scripts/check_regulatory_sources.py` fetched every cited source again and searched for the "
         "evidence phrase recorded with the statement; sources that cannot be read by a script (an image-only gazette page, blocked "
         "sites, secondary-only evidence) were re-read by hand and are marked `manual`. The result per statement is below.", ""]
    if log:
        L.append(f"Re-check run: {log.get('run_date', '?')}; phrases found {log.get('found', 0)}, manual {log.get('manual', 0)}, "
                 f"not found {log.get('not_found', 0)}, fetch errors {log.get('errors', 0)}.")
        L.append("")
    L += ["## Corrections to the initial plan", "",
          "- **ATA Carnet issuer in Singapore.** The initial plan named the Singapore Business Federation as the issuer. Singapore Customs (page updated "
          "31 Jul 2026), the ICC directory of national guaranteeing associations and SICC itself name the **Singapore International "
          "Chamber of Commerce (SICC)**; no carnet role for SBF was found (statement `SG-ATA-ISSUER`).",
          "- **ATA purposes accepted by Singapore.** The initial plan listed commercial samples among ATA uses. For imports into Singapore, "
          "Singapore Customs lists only exhibitions/fairs, professional equipment and scientific equipment for tests or demonstrations "
          "(`SG-ATA-SCOPE`, `SG-ATA-NO-SAMPLES`).",
          "- **Thailand's low-value rule.** The THB 1,500 duty exemption no longer applies: Customs Notification 219/2568 limits the "
          "exemption to items worth up to 1 baht from 1 January 2026 (`TH-DUTY-1BAHT`).", "",
          "## Changes made in the second pass", "",
          "- `SG-TIS-SECURITY`: the security page distinguishes selected and non-selected goods. The selected-goods list "
          "(Singapore Customs PDF) was read and does not include the template's equipment, so the 30% share for a GST-registered "
          "entity stands; the list was added as a source.",
          "- `PH-DEMINIMIS`: a clause on excise for de minimis tobacco and alcohol came from an older Department of Finance release "
          "about the first implementing order; it was removed because the current order could not be read.",
          "- `FTA-RCEP-B2B`: the evidence phrase sat across a hyphenated line break in the implementing-guidelines PDF, so the "
          "automated search missed it; the check now points to the heading of Article 3.19 in the agreement text.",
          "- Thai Customs Notification 219/2568 was downloaded again (identical SHA-256) and its rendered page re-read.", "",
          "## Statements", "",
          "| ID | Jurisdiction | Status | Statement | Sources | Re-check | Note |", "|---|---|---|---|---|---|---|"]
    entries = (log or {}).get("statements", {})
    for sid in sorted(statements):
        st = statements[sid]
        srcs = ", ".join(_link(sources, s) for s in st.get("sources", [])) or "-"
        chk = entries.get(sid, {}).get("result", "not run")
        L.append(f"| `{sid}` | {st['jurisdiction']} | {st['status']} | {_esc(st['en'])} | {srcs} | {chk} | {_esc(st.get('note', ''))} |")
    nv = [sid for sid in sorted(statements) if statements[sid]["status"] == "not_verified"]
    L += ["", "## Not verified (placeholders or caveats in the kit)", ""]
    for sid in nv:
        L.append(f"- `{sid}`: {statements[sid]['en']}")
    return "\n".join(L) + "\n"
